def render_effects(locations: list[dict], items: list[dict]) -> str:
    technologies = of_kind(locations, "technology")
    report = "".join(
        f'\tif = {{ limit = {{ has_technology = {tech_key(location)} }} log = "AP_CHECK {location["id"]}" }}\n'
        for location in technologies)
    report_last = "".join(
        f'\tif = {{ limit = {{ last_increased_tech = {tech_key(location)} }} log = "AP_CHECK {location["id"]}" }}\n'
        for location in technologies)
    perks = "".join(
        f'\tif = {{ limit = {{ num_ascension_perks >= {location["number"]} }} log = "AP_CHECK {location["id"]}" }}\n'
        for location in of_kind(locations, "perk"))
    grant = "".join(
        f"\tif = {{ limit = {{ check_variable = {{ which = ap_last_item value = {item['id']} }} }} "
        f"{' '.join(item['effect'].split())} }}\n"
        for item in items)
    dlcs = "".join(f'\tif = {{ limit = {{ host_has_dlc = "{dlc}" }} log = "AP_DLC {number}" }}\n'
                   for number, dlc in enumerate(data.dlcs(), 1))
    return (f"{HEADER}\n# Reports every check done so far\n# Scope: country\n"
            f"ap_report_checks = {{\n{report}\tap_report_picks = yes\n}}\n"
            f"\n# Reports the DLCs of the game and the kind of empire of the player, which the client compares\n"
            f"# with the options the multiworld was made with\n# Scope: country\n"
            f"ap_report_setup = {{\n{dlcs}"
            f"\tif = {{ limit = {{ has_authority = auth_hive_mind }} log = \"AP_EMPIRE 2\" }}\n"
            f"\telse_if = {{ limit = {{ has_authority = auth_machine_intelligence }} log = \"AP_EMPIRE 3\" }}\n"
            f"\telse = {{ log = \"AP_EMPIRE 1\" }}\n}}\n"
            f"\n# Reports the check that was just researched\n# Scope: country\n"
            f"ap_report_last_check = {{\n{report_last}}}\n"
            + render_tree_effects(data.tradition_trees()) % perks
            + render_received_traditions()
            + f"\n# Grants the item whose id is in ap_last_item\n# Scope: country\nap_grant_item = {{\n{grant}}}\n")


def render_scripted_loc(items: list[dict]) -> str:
    """[Root.GetAPItemName] and [Root.GetAPSenderName]: the item that arrived last, and who sent it."""
    def texts(variable: str, key: str, numbers) -> str:
        return "".join(f"\ttext = {{ trigger = {{ check_variable = {{ which = {variable} value = {number} }} }} "
                       f"localization_key = {key}_{number} }}\n" for number in numbers)

    out = (f"{HEADER}\n# Scope: country\ndefined_text = {{\n\tname = GetAPItemName\n\trandom = no\n"
           f"{texts('ap_last_item', 'ap_item', [item['id'] for item in items])}\tdefault = ap_item_unknown\n}}\n"
           f"\n# Scope: country\ndefined_text = {{\n\tname = GetAPSenderName\n\trandom = no\n"
           f"{texts('ap_last_sender', 'ap_sender', range(1, MAX_SENDERS + 1))}\tdefault = ap_sender_0\n}}\n"
           # What the last death took
           f"\n# Scope: country\ndefined_text = {{\n\tname = GetAPDeathEffect\n\trandom = no\n"
           f"{texts('ap_death_effect', 'ap_death_effect', DEATH_EFFECT_TEXTS)}\tdefault = ap_death_effect_0\n}}\n")
    return out


def render_localisation(language: str) -> str:
    texts = dict(EVENT_TEXT)
    texts.update({f"ap_item_{item['id']}": clean(item["name"]) for item in data.items()})
    for tree in data.normal_trees():
        # The tree of the real traditions goes by the name of the tree of the game
        texts[real_tree(tree["key"])] = f"${tree['key']}$"
        for position, tradition in enumerate(tree["traditions"]):
            key = check_tradition(tradition["key"])
            # The text under the name of a tradition has the key <name>_delayed. The tooltip says it all
            texts[key] = "$ap_loc_none_name$"
            texts[key + "_delayed"] = ""
            for slot in range(data.TREE_SLOTS):
                # The name of the location, which the client writes for every multiworld
                texts[swap_name(key, slot)] = f"$ap_loc_{data.tradition_location(slot, position)}_name$"
                texts[swap_name(key, slot) + "_delayed"] = ""
    return f"l_{language}:\n" + "".join(f' {key}:0 "{text}"\n' for key, text in texts.items())


def clean(text: str) -> str:
    """A name from another game, without the characters that mean something in localisation."""
    return "".join("'" if character == '"' else character for character in text
                   if character not in "$[]§£\\\n\r")


def render_check_names(locations: list[dict], language: str, names: dict[int, tuple[str, str]] | None = None,
                       players: dict[int, str] | None = None) -> str:
    """names: {location id: (name of the item there, name of the player it is for)}, when known.
    players: {slot: name} of the players of the multiworld, who can send items."""
    out = [f"l_{language}:\n", ' ap_sender_0:0 "Archipelago"\n']
    for slot in range(1, MAX_SENDERS + 1):
        out.append(f' ap_sender_{slot}:0 "{clean((players or {}).get(slot, f"Player {slot}"))}"\n')
    for location in locations:
        named = names and location["id"] in names
        item, player = (clean(text) for text in names[location["id"]]) if named else ("", "")
        if location["kind"] == "technology":
            key = tech_key(location)
            if named:
                out.append(f' {key}:0 "Archipelago: {item}"\n')
                out.append(f' {key}_desc:0 "Researching this sends §Y{item}§! to §Y{player}§!."\n')
            else:
                out.append(f' {key}:0 "Archipelago Check"\n')
                out.append(f' {key}_desc:0 "Researching this sends a check to the multiworld."\n')
        elif location["kind"] == "tradition":
            # Shown by whichever tradition is this location in the running game, as its name and tooltip
            text = f"Sends §Y{item}§! to §Y{player}§!." if named else "Sends a check to the multiworld."
            out.append(f' ap_loc_{location["id"]}:0 "{text}"\n')
            out.append(f' ap_loc_{location["id"]}_name:0 "{f"Archipelago: {item}" if named else "Archipelago Check"}"\n')
    return "".join(out)


def write_check_names(names: dict[int, tuple[str, str]] | None = None, players: dict[int, str] | None = None) -> None:
    """Names the technologies after the items of a multiworld, and its players. The game reads them when it starts."""
    for language in LANGUAGES:
        # Localisation files must be UTF-8 with BOM
        write(MOD_DIR / "localisation" / language / f"ap_check_names_l_{language}.yml",
              render_check_names(data.locations(), language, names, players), encoding="utf-8-sig")


def render_session(run: int = 0, items=(), checked=(), vanilla_traditions: bool = False) -> str:
    """ap_start_run, which the mod calls when a new game starts: the game belongs to the run right away, and
    has what the run has received so far. That is how a player who lost goes on with a new game.

    items: every item received so far, in order. All of them are granted again, without their messages:
    technologies, traditions, ascension perk slots and resources. For every Random Event a new one is
    played some time into the game, one after the other, which need not be the same as the first time.
    checked: the ids of the locations that are done. Their technologies count as researched.
    vanilla_traditions: the traditions are not shuffled, the player has the trees of the game.
    """
    lines = []
    if run:
        lines.append(f"\tset_variable = {{ which = ap_run value = {run} }}\n")
        if vanilla_traditions:
            # Nothing is received that would make traditions more expensive
            lines.append(f"\tset_country_flag = {VANILLA_TRADITIONS}\n\tremove_modifier = ap_tradition_cost\n")
        events = 0
        for item in items:
            if item["name"] == data.tables.RANDOM_EVENT:
                lines.append(f"\tcountry_event = {{ id = ap.23 days = "
                             f"{REPLAY_FIRST_DAY + REPLAY_DAYS_APART * events} }}\n")
                events += 1
            else:
                lines.append(f"\t{item['effect'].replace('message = yes', 'message = no')}\n")
        # The game goes on with the items that come after these
        lines.append(f"\tset_variable = {{ which = ap_item_index value = {len(items)} }}\n")
        technologies = {location["id"]: location for location in of_kind(data.locations(), "technology")}
        for location in sorted(set(checked) & set(technologies)):
            lines.append(f"\tgive_technology = {{ tech = {tech_key(technologies[location])} message = no }}\n")
    return ("# Written by the client for the run that is played, do not edit. Empty while no client runs.\n"
            f"\n# Scope: country\nap_start_run = {{\n{''.join(lines)}}}\n")


def write_session(run: int = 0, items=(), checked=(), vanilla_traditions: bool = False) -> None:
    """Like the names, the game reads this when it starts."""
    write(MOD_DIR / "common" / "scripted_effects" / SESSION_FILE,
          render_session(run, items, checked, vanilla_traditions))


def random_event_pool(text: str, names) -> dict[str, int]:
    """{event: weight} of the random events of some on_actions of the game, from the text of their file."""
    pool: dict[str, int] = {}
    for key, opened, closed in pdx.block_spans(text):
        if key not in names:
            continue
        for inner, start, end in pdx.block_spans(text, opened + 1, closed):
            if inner != "random_events":
                continue
            for weight, event in re.findall(r"(\d+)\s*=\s*([\w.]+)", re.sub(r"#.*", "", text[start + 1:end])):
                # 0 is the chance of no event at all, and a weight of 0 an event that is switched off
                if event != "0" and int(weight):
                    pool[event] = max(pool.get(event, 0), int(weight))
    return pool


def render_random_events(game_dir) -> str:
    """The on_actions the item Random Event fires, each with the events of the game's own lists."""
    text = "".join(path.read_text(encoding="utf-8-sig", errors="replace")
                   for path in sorted((game_dir / "common" / "on_actions").glob("*.txt")))
    out = [HEADER, "# The random events of the game, from its on_actions. Which of them can come up is up to\n"
                   "# the triggers of the events themselves, as it is when the game brings them up\n"]
    for name, sources in RANDOM_EVENT_POOLS.items():
        events = "".join(f"\t\t{weight} = {event}\n"
                         for event, weight in sorted(random_event_pool(text, sources).items()))
        out.append(f"\n{name} = {{\n\trandom_events = {{\n{events}\t}}\n}}\n")
    return "".join(out)


def render_icon(source, size: int = ICON_SIZE) -> bytes:
    """The icon as an uncompressed 32 bit DDS, the format of the vanilla technology and tradition icons."""
    from PIL import Image

    image = Image.open(source).convert("RGBA")
    image = image.crop(image.getbbox())
    side = max(image.size)
    square = Image.new("RGBA", (side, side))
    square.paste(image, ((side - image.width) // 2, (side - image.height) // 2))
    pixels = square.resize((size, size), Image.LANCZOS).tobytes("raw", "BGRA")
    header = struct.pack(
        "<4s7I44x8I4I4x",
        b"DDS ", 124, 0x81007, size, size, len(pixels), 0, 0,  # flags: caps, size, format, linear size
        32, 0x41, 0, 32, 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000,  # pixel format: RGB with alpha
        0x1000, 0, 0, 0)  # caps: texture
    return header + pixels


def write(path, text: str, encoding: str = "utf-8") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding=encoding, newline="\n")


def build(game_dir) -> None:
    locations = data.locations()
    technology_dir = MOD_DIR / "common" / "technology"
    for path in technology_dir.glob("*.txt"):
        path.unlink()
    write(technology_dir / CHECKS_FILE, render_technologies(locations))
    overrides = render_overrides(game_dir)
    for name, text in overrides.items():
        write(technology_dir / name, text)
    write(MOD_DIR / "common" / "traditions" / TRADITIONS_FILE, render_traditions(data.tradition_trees()))
    category_dir = MOD_DIR / "common" / "tradition_categories"
    for path in category_dir.glob("*.txt"):
        path.unlink()
    for name, text in render_tradition_categories(game_dir).items():
        write(category_dir / name, text)
    write(MOD_DIR / "interface" / "ap_traditions.gfx", render_tradition_sprites(data.tradition_trees()))
    write(MOD_DIR / "interface" / TRADITION_WINDOW_FILE,
          render_tradition_window((game_dir / "interface" / TRADITION_WINDOW_FILE).read_text(encoding="utf-8-sig")))
    write(MOD_DIR / "common" / "defines" / "ap_defines.txt", render_defines())
    write(MOD_DIR / "common" / "scripted_triggers" / "ap_triggers.txt", render_triggers(data.tradition_trees()))
    write(MOD_DIR / "common" / "ascension_perks" / ASCENSION_PATHS_FILE, render_ascension_paths(
        (game_dir / "common" / "ascension_perks" / ASCENSION_PATHS_FILE).read_text(encoding="utf-8-sig")))
    write(MOD_DIR / "common" / "on_actions" / RANDOM_EVENTS_FILE, render_random_events(game_dir))
    write(MOD_DIR / "common" / "scripted_effects" / "ap_generated_effects.txt",
          render_effects(locations, data.items()))
    write(MOD_DIR / "common" / "scripted_loc" / "ap_scripted_loc.txt", render_scripted_loc(data.items()))
    for language in LANGUAGES:
        write(MOD_DIR / "localisation" / language / f"ap_l_{language}.yml",
              render_localisation(language), encoding="utf-8-sig")
    write_check_names()
    write_session()
    if ICON_SOURCE.is_file():
        try:
            icon = render_icon(ICON_SOURCE)
        except ImportError:
            print("Pillow is not installed, keeping the existing technology icon")
        else:
            ICON_PATH.parent.mkdir(parents=True, exist_ok=True)
            ICON_PATH.write_bytes(icon)
            (MOD_DIR / TRADITION_ICON).parent.mkdir(parents=True, exist_ok=True)
            (MOD_DIR / TRADITION_ICON).write_bytes(render_icon(ICON_SOURCE, TRADITION_ICON_SIZE))
    print(f"Generated {len(locations)} checks and {len(overrides)} technology files into {MOD_DIR}")


def register(user_dir, mod_dirs=(MOD_DIR,)) -> bool:
    """Tells the Stellaris launcher where the mod is. Returns whether that was new to it.

    The launcher finds a mod through a file in the user's mod folder, which holds the path of the mod.
    """
    changed = False
    for mod_dir in mod_dirs:
        descriptor = (mod_dir / "descriptor.mod").read_text(encoding="utf-8")
        target = user_dir / "mod" / f"{mod_dir.name}.mod"
        text = f'{descriptor}path="{mod_dir.as_posix()}"\n'
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            write(target, text)
            changed = True
    return changed


def install(user_dir) -> None:
    try:
        register(user_dir, (MOD_DIR, HIDDEN_CONSOLE_MOD_DIR))
    except OSError as error:
        sys.exit(WRITE_BLOCKED_HINT.format(path=error.filename, python=sys.executable))
    print(f"Registered the mods in {user_dir / 'mod'}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--install", action="store_true", help="register the mod with the Stellaris launcher")
    parser.add_argument("--stellaris-dir", help="Stellaris user directory (default: auto detect)")
    parser.add_argument("--game-dir", help="Stellaris install directory (default: found through Steam)")
    args = parser.parse_args()
    game_dir = stellaris_game_dir(args.game_dir)
    if game_dir is None:
        sys.exit("Stellaris install not found, pass --game-dir")
    build(game_dir)
    if args.install:
        install(stellaris_user_dir(args.stellaris_dir))


if __name__ == "__main__":
    main()
