def check_tradition(key: str) -> str:
    """The key of the tradition that is picked as a location, in place of this tradition."""
    return "tr_ap_" + key.removeprefix("tr_")


def real_tree(key: str) -> str:
    """The key of the tree with the real traditions, which the AI countries use."""
    return "tradition_ap_real_" + key.removeprefix("tradition_")


def short(tree: dict) -> str:
    """The name of a tree in flags, variables and scripted localisation."""
    return tree["key"].removeprefix("tradition_")


def picked_keys(tree: dict) -> list[str]:
    """The traditions the player picks in a tree, in order: locations in a normal tree, the real ones otherwise."""
    return [check_tradition(tradition["key"]) if tree["kind"] == "normal" else tradition["key"]
            for tradition in tree["traditions"]]


def tech_key(location: dict) -> str:
    """The key of the technology that is researched for a location."""
    return f"ap_check_{location['id']}"


def of_kind(locations: list[dict], kind: str) -> list[dict]:
    return [location for location in locations if location["kind"] == kind]


def render_technologies(locations: list[dict]) -> str:
    """The technology to research for each location: where its technology was, and as expensive."""
    out = [HEADER]
    for location in of_kind(locations, "technology"):
        technology = location["technology"]
        tier = technology["tier"]
        out.append(f"""
# {technology['name']}
{tech_key(location)} = {{
	area = {technology['area']}
	cost = {min(technology['cost'] or TIER_COST[tier], MAX_COST)}
	tier = {tier}
	category = {{ {technology['category']} }}
	weight = {technology['weight'] or TIER_WEIGHT[tier]:g}
	icon = {ICON_NAME}

	potential = {{
		{NOT_AI}
	}}
}}
""")
    return "".join(out)


def render_override(text: str, hidden: set[str]) -> str:
    """A technology file of the game, in which the hidden technologies are never offered to the player."""
    inserts = []
    for key, opened, closed in pdx.block_spans(text):
        if key not in hidden:
            continue
        inner = {name: end for name, _, end in pdx.block_spans(text, opened + 1, closed)}
        if "weight_modifier" in inner:
            inserts.append((inner["weight_modifier"], f"\t{HIDE}\n\t"))
        else:
            inserts.append((closed, f"\tweight_modifier = {{ {HIDE} }}\n"))
    for position, insert in sorted(inserts, reverse=True):
        text = text[:position] + insert + text[position:]
    return ("# The game's file with one change, generated by stellaris_ap.build_mod: the technologies that are\n"
            "# Archipelago items get the weight 0 for the player, who receives them as items instead.\n" + text)


def hidden_technologies() -> set[str]:
    """The item technologies the game would offer as research. The others only come from events."""
    return {technology["key"] for technology in data.technologies()
            if technology["kind"] == "item" and technology["weight"] > 0}


def render_overrides(game_dir) -> dict[str, str]:
    """{file name: content} for every technology file of the game with a hidden technology."""
    hidden = hidden_technologies()
    files = {technology["file"] for technology in data.technologies() if technology["key"] in hidden}
    return {name: render_override((game_dir / "common" / "technology" / name).read_text(encoding="utf-8-sig"), hidden)
            for name in sorted(files)}


def swap_name(key: str, slot: int) -> str:
    """The name a tradition location goes by when its tree is the one adopted as number slot."""
    return f"{key}_s{slot}"


def render_traditions(trees: list[dict]) -> str:
    """The traditions that are picked as locations. They do nothing, and keep the order of the tree.

    Which location a tradition is depends on the number of its tree. The name of a tradition cannot
    depend on anything, but a tradition swap can give it another name: there is one for every number.
    """
    out = [HEADER]
    for tree in trees:
        if tree["kind"] != "normal":
            continue
        out.append(f"\n# {tree['name']}\n")
        for position, tradition in enumerate(tree["traditions"]):
            key = check_tradition(tradition["key"])
            possible = "".join(f"\t\thas_tradition = {check_tradition(required)}\n" for required in tradition["requires"])
            swaps = "".join(
                f"\ttradition_swap = {{\n\t\tname = {swap_name(key, slot)}\n\t\tinherit_icon = yes\n"
                f"\t\tinherit_effects = no\n"
                f"\t\ttrigger = {{ check_variable = {{ which = ap_slot_{short(tree)} value = {slot} }} }}\n"
                f"\t\tcustom_tooltip = ap_loc_{data.tradition_location(slot, position)}\n"
                f"\t\tweight = {{ factor = 1 }}\n\t}}\n" for slot in range(data.TREE_SLOTS))
            out.append(f"\n# {tradition['name']}\n{key} = {{\n"
                       + (f"\tpossible = {{\n{possible}\t}}\n" if possible else "")
                       + f"\tcustom_tooltip = ap_loc_none\n{swaps}\tai_weight = {{ factor = 0 }}\n}}\n")
    return "".join(out)


def with_potential(block: str, trigger: str) -> str:
    """A tree "{ ... }" of the game, with one more condition for who can have it."""
    inner = {name: start for name, start, _ in pdx.block_spans(block, 1, len(block) - 1)}
    if "potential" in inner:
        position = inner["potential"] + 1
        return block[:position] + f"\n\t\t{trigger}" + block[position:]
    return block[:-1] + f"\tpotential = {{ {trigger} }}\n}}"


def adoption(tree: dict) -> str:
    """The key of the tradition that adopting a tree gives."""
    return next(tradition["key"] for tradition in tree["traditions"] if tradition["role"] == "adopt")


def render_tradition_category(text: str, tree: dict) -> str:
    """A tradition tree file of the game: the tree with locations for the player, and the real one for the AI.
    Either can be adopted while the empire has a place for one more tree, see render_triggers."""
    opened, closed = next((opened, closed) for key, opened, closed in pdx.block_spans(text) if key == tree["key"])
    block = text[opened:closed + 1]
    checks = block
    for tradition in tree["traditions"]:
        checks = re.sub(rf'"{tradition["key"]}"', f'"{check_tradition(tradition["key"])}"', checks)
    mine = f"{NOT_AI} {NOT_VANILLA} OR = {{ has_tradition = {check_tradition(adoption(tree))} {SLOT_FREE} }}"
    real = f"{REAL_TREES} OR = {{ has_tradition = {adoption(tree)} {SLOT_FREE} }}"
    return (f"{HEADER}\n# For the player: the tree of the game, with a location in place of every tradition\n"
            f"{tree['key']} = {with_potential(checks, mine)}\n"
            f"\n# For the AI countries, and for a player whose traditions are not shuffled: the tree of the game\n"
            f"{real_tree(tree['key'])} = {with_potential(block, real)}\n")


def render_tradition_categories(game_dir) -> dict[str, str]:
    """{file name: content} for the files of the normal tradition trees of the game."""
    folder = game_dir / "common" / "tradition_categories"
    return {tree["file"]: render_tradition_category((folder / tree["file"]).read_text(encoding="utf-8-sig"), tree)
            for tree in data.tradition_trees() if tree["kind"] == "normal"}


def trees_max() -> int:
    """How many trees the game lets an empire have: its seven, and the tree of every tradition it can receive."""
    return data.TREE_SLOTS + len(data.normal_trees())


def render_defines() -> str:
    """The game counts the tree of every tradition an empire owns as one of its trees, also one that was received
    and not adopted, and lets it adopt no more once there are TRADITION_CATEGORIES_MAX. That is raised so far that
    received traditions can not use the places up, and the seven trees an empire adopts are counted by the mod."""
    return f"{HEADER}NGameplay = {{\n\tTRADITION_CATEGORIES_MAX = {trees_max()}\n}}\n"


def render_triggers(trees: list[dict]) -> str:
    """ap_tree_slot_free: whether an empire has adopted fewer than seven trees, counted by the traditions that
    adopting one gives: the trees of the player, of the AI, and of the ascension paths, which count as well."""
    adopted = []
    for tree in trees:
        if tree["kind"] == "normal":
            adopted.append(check_tradition(adoption(tree)))
        adopted.append(adoption(tree))
    lines = "".join(f"\t\t\thas_tradition = {key}\n" for key in adopted)
    return (f"{HEADER}\n# Whether the empire can adopt one more tradition tree, in place of the limit of the game: "
            f"see\n# render_defines in build_mod.py\n# Scope: country\nap_tree_slot_free = {{\n\tNOT = {{\n"
            f"\t\tcalc_true_if = {{\n\t\t\tamount >= {data.TREE_SLOTS}\n{lines}\t\t}}\n\t}}\n}}\n")


def render_ascension_paths(text: str) -> str:
    """The ascension paths of the game, which take a place for their tree: counted by the mod, see render_defines."""
    limit = "num_tradition_categories < @max_tradition_trees"
    assert limit in text, "the game changed how an ascension path takes a tree"
    return HEADER + text.replace(limit, SLOT_FREE)


