def render_tree_effects(trees: list[dict]) -> str:
    """Tradition locations are told apart by the order in which their trees were adopted.

    ap_trees_adopted counts the adopted trees. ap_slot_<tree> is the number (from 0) under which a tree
    was adopted, or will be if it is the next: the tooltips of its traditions are picked with it.
    """
    init = "\tset_variable = { which = ap_trees_adopted value = 0 }\n" + "".join(
        f"\tset_variable = {{ which = ap_slot_{short(tree)} value = 0 }}\n" for tree in trees)
    assign = "".join(
        f"\tif = {{\n\t\tlimit = {{ has_tradition = {picked_keys(tree)[0]} "
        f"NOT = {{ has_country_flag = ap_tree_{short(tree)} }} }}\n"
        f"\t\tset_country_flag = ap_tree_{short(tree)}\n"
        f"\t\tset_variable = {{ which = ap_slot_{short(tree)} value = ap_trees_adopted }}\n"
        f"\t\tchange_variable = {{ which = ap_trees_adopted value = 1 }}\n\t}}\n" for tree in trees)
    assign += "".join(
        f"\tif = {{ limit = {{ NOT = {{ has_country_flag = ap_tree_{short(tree)} }} }} "
        f"set_variable = {{ which = ap_slot_{short(tree)} value = ap_trees_adopted }} }}\n" for tree in trees)
    picks = ""
    for tree in trees:
        picks += f"\tif = {{\n\t\tlimit = {{ has_country_flag = ap_tree_{short(tree)} }}\n"
        for slot in range(data.TREE_SLOTS):
            picks += (f"\t\tif = {{\n\t\t\tlimit = {{ check_variable = "
                      f"{{ which = ap_slot_{short(tree)} value = {slot} }} }}\n")
            for position, key in enumerate(picked_keys(tree)):
                picks += (f'\t\t\tif = {{ limit = {{ has_tradition = {key} }} '
                          f'log = "AP_CHECK {data.tradition_location(slot, position)}" }}\n')
            picks += "\t\t}\n"
        picks += "\t}\n"
    return (f"\n# Scope: country\nap_init_tree_slots = {{\n{init}}}\n"
            f"\n# Gives the tree that was just adopted its number\n# Scope: country\n"
            f"ap_assign_tree_slots = {{\n{assign}}}\n"
            f"\n# Reports the traditions and ascension perks picked so far\n# Scope: country\n"
            f"ap_report_picks = {{\n{picks}%s}}\n")


